#!/usr/bin/env node
// Derives the files the app loads from the shared sources, which stay unchanged:
//
//   art/icons/*.svg, art/glyphs/*.svg  ->  assets/art/{icons,glyphs}/<name>{,@2x,@3x}.png  and  src/generated/art.ts
//   art/launcher.svg                   ->  assets/launcher/*.png (app icon, Android adaptive layers, notification icon)
//   assets/web/care-guide.html         ->  src/generated/careGuide.ts (the page as a string, byte for byte)
//
// React Native's Image cannot draw SVG, and react-native-svg is a community package, so the drawings ship as PNGs at
// 1x, 2x and 3x. Strokes are drawn black on transparent; the app tints them with Image's tintColor, so one PNG serves
// every aisle ink and both themes. @resvg/resvg-js is a build-only tool: it never ships in the app.
//
// Run it with `npm run derive` after changing art/ or care-guide.html, and commit what it writes. The tests fail when
// the derived files no longer match their sources.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const at = (...parts) => join(root, ...parts);

/** dp size of the 1x PNG. Icons are shown at 16–40 dp and glyphs at 35–136 dp, so each is drawn at its largest use. */
const BASE = { icons: 48, glyphs: 144 };
const SCALES = [1, 2, 3];

function render(svg, width) {
  return new Resvg(svg, { fitTo: { mode: 'width', value: width }, font: { loadSystemFonts: false } }).render().asPng();
}

function strokeInBlack(svg) {
  return svg.replaceAll('currentColor', '#000000');
}

const generated = [];
function write(path, data) {
  mkdirSync(dirname(at(path)), { recursive: true });
  writeFileSync(at(path), data);
  generated.push(path);
}

// 1. Icons and glyphs.
rmSync(at('assets/art'), { recursive: true, force: true });
const names = {};
for (const kind of ['icons', 'glyphs']) {
  names[kind] = readdirSync(at('art', kind)).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort();
  for (const name of names[kind]) {
    const svg = strokeInBlack(readFileSync(at('art', kind, `${name}.svg`), 'utf8'));
    for (const scale of SCALES) {
      const suffix = scale === 1 ? '' : `@${scale}x`;
      write(`assets/art/${kind}/${name}${suffix}.png`, render(svg, BASE[kind] * scale));
    }
  }
}

// The gift cards' Stone design: three pebbles, drawn for that card as the Android app draws them, in the glyphs'
// 2.5-unit stroke. It is not in art/ because it is not a product drawing.
const pebbles = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 36" width="64" height="36" fill="none" stroke="#000000" stroke-width="2.5">
<ellipse cx="13.44" cy="23.4" rx="12.19" ry="9.55"/><ellipse cx="34" cy="9" rx="9.63" ry="7.75"/><ellipse cx="50.08" cy="25.56" rx="12.83" ry="8.11"/></svg>`;
for (const scale of SCALES) {
  write(`assets/art/extra/pebbles${scale === 1 ? '' : `@${scale}x`}.png`, render(pebbles, 64 * scale));
}

// 2. The launcher mark. Its three shapes, in order: the drawer front, the brass label holder, the pull.
const launcher = readFileSync(at('art/launcher.svg'), 'utf8');
const shapes = [...launcher.matchAll(/<path [^>]*d="([^"]+)"/g)].map((m) => m[1]);
if (shapes.length !== 3) throw new Error(`launcher.svg: expected 3 paths, found ${shapes.length}`);
const [drawer, holder, pull] = shapes;
write('assets/launcher/icon.png', render(launcher, 1024));
// Android's adaptive icon: the mark without its square, over a green background layer (app.json).
write('assets/launcher/adaptive-foreground.png', render(launcher.replace(/<rect [^>]*\/>/, ''), 1024));
// A one-colour silhouette for Android 13 themed icons and the notification icon: the drawer front, with the label
// holder and the pull cut out of it.
const silhouette = (viewBox, size) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${size}" height="${size}">
<defs><mask id="cut"><rect x="0" y="0" width="108" height="108" fill="#FFFFFF"/>
<path d="${holder}" fill="none" stroke="#000000" stroke-width="3"/>
<path d="${pull}" fill="none" stroke="#000000" stroke-width="4" stroke-linecap="round"/></mask></defs>
<path d="${drawer}" fill="#FFFFFF" mask="url(#cut)"/></svg>`;
write('assets/launcher/adaptive-monochrome.png', render(silhouette('0 0 108 108', 1024), 1024));
write('assets/launcher/notification.png', render(silhouette('22 22 64 64', 96), 96));

// 3. The modules that name the derived files (Metro needs a literal require for each image).
const banner = '// Generated by scripts/derive-assets.mjs from the shared sources. Do not edit; run `npm run derive`.\n';
const requireMap = (kind, list) =>
  `export const ${kind === 'icons' ? 'ICONS' : 'GLYPHS'} = {\n` +
  list.map((n) => `  ${/^[a-z]+$/.test(n) ? n : `'${n}'`}: require('../../assets/art/${kind}/${n}.png'),`).join('\n') +
  '\n} as const;\n';
write(
  'src/generated/art.ts',
  banner +
    '/* eslint-disable @typescript-eslint/no-require-imports */\n' +
    `${requireMap('icons', names.icons)}\n${requireMap('glyphs', names.glyphs)}\n` +
    "export const PEBBLES = require('../../assets/art/extra/pebbles.png');\n\n" +
    `/** dp size of each 1x PNG. */\nexport const ART_BASE = ${JSON.stringify(BASE)} as const;\n`,
);

const page = readFileSync(at('assets/web/care-guide.html'), 'utf8');
write(
  'src/generated/careGuide.ts',
  banner + '/** assets/web/care-guide.html, unchanged, as the string the web view loads. */\n' +
    `export const CARE_GUIDE_HTML = ${JSON.stringify(page)};\n`,
);

console.log(`derive-assets: wrote ${generated.length} files`);
